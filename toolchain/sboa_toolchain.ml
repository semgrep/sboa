(* The toolchain facts compiled in from Sboa_toolchain_data (generated by
   describe.py). See the .mli. *)

let version = Sboa_toolchain_data.version
let platform = Sboa_toolchain_data.platform
let external_libdynload_dir = Sboa_toolchain_data.external_libdynload_dir

let is_dir path =
  (* sboa is standalone: no Sys_/Fpath_ here; the path is a plain local
     directory (Windows never gets an external lib-dynload). *)
  (* nosemgrep: no-sys-file-exists *)
  match Sys.is_directory path with
  | b -> b
  | exception Sys_error _ -> false

(* Same default as sboa's C side (py_libdynload_dir in
   src/cpython/sboa_export.c). *)
let exe_relative_libdynload_dir () =
  Filename.concat
    (Filename.dirname Sys.executable_name)
    Sboa_toolchain_data.default_libdynload_rel

let libdynload_dir () =
  match external_libdynload_dir with
  | None -> None
  | Some _ when is_dir (exe_relative_libdynload_dir ()) -> None
  | Some _ as ext -> ext
